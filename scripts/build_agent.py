#!/usr/bin/env python3
"""Generate .claude/agents/karpathy.md from the wiki. Never edit that file by hand.

Reads promoted principles (wiki/principles/*.md), bench principles
(wiki/principles/_bench/*.md) and the voice method (wiki/methods/how-he-explains.md), and
writes the sub-agent: frontmatter with the run-gate hooks, then Grounding, Rules, Voice,
Task loop, Working folder and Report. Output is deterministic (sorted by slug). Fails if a
principle has no quote, a quote's source page does not exist, or the voice page is missing.

`render()` takes the paths to write into the file, so scripts/install.py can render a
user-level copy with absolute paths while the repo copy stays relative.

Usage: python3 scripts/build_agent.py [--root PATH] [--check]
  --check  exit 1 if the committed agent file is out of date
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import lint_check as L  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ".claude/agents/karpathy.md"
REPO_WIKI = "."
REPO_HOOK = "$CLAUDE_PROJECT_DIR/.claude/hooks/run_gate.py"
USER_HOOK = "$HOME/.claude/hooks/karpathy-run-gate.py"  # linked by scripts/install.py


def hook_command(hook, mode):
    """Shell command for a hook: the given path, falling back to the user-level link.

    The repo copy of the agent can be loaded from another project (e.g. with --add-dir),
    where $CLAUDE_PROJECT_DIR is that project, so it must not depend on it alone."""
    return (f'f="{hook}"; [ -f "$f" ] || f="{USER_HOOK}"; python3 "$f" {mode}')
VOICE = "wiki/methods/how-he-explains.md"


class BuildError(Exception):
    pass


def read(path):
    meta, body = L.split_frontmatter(path.read_text(encoding="utf-8"))
    if not isinstance(meta, dict):
        raise BuildError(f"no frontmatter: {path}")
    title = next((l[2:].strip() for l in body.splitlines() if l.startswith("# ")), path.stem)
    return meta, body, title


def principles(root, folder):
    out = []
    for p in sorted((root / "wiki" / folder).glob("*.md")):
        meta, body, title = read(p)
        if meta.get("type") != "principle":
            continue
        quotes = [q for q in meta.get("quotes") or [] if isinstance(q, dict) and q.get("text")]
        if not quotes:
            raise BuildError(f"principle without a quote: {p}")
        for q in quotes:
            for s in L.links_in(q.get("source", "")):
                if not (root / "wiki" / "sources" / f"{s}.md").exists():
                    raise BuildError(f"quote source not found: {s} in {p}")
        out.append({"slug": p.stem, "title": title, "quote": quotes[0],
                    "inferred": meta.get("inferred") is True,
                    "path": f"wiki/{folder}/{p.stem}.md"})
    return out


def voice_steps(root):
    p = root / VOICE
    if not p.exists():
        raise BuildError(f"voice page missing: {VOICE}")
    meta, _, _ = read(p)
    steps = meta.get("steps") or []
    if not steps:
        raise BuildError(f"voice page has no steps: {VOICE}")
    return [str(s) for s in steps]


def quote_line(q):
    src = ", ".join(L.links_in(q.get("source", "")))
    return f'"{q["text"]}" ({src} {q.get("location", "")}'.rstrip() + ")"


def render(root, wiki, hook):
    promoted = principles(root, "principles")
    bench = principles(root, "principles/_bench")
    steps = voice_steps(root)
    if not promoted:
        raise BuildError("no promoted principles")
    w = wiki.rstrip("/")
    lines = [
        "---",
        "name: karpathy",
        "description: Teaches and reviews code the way Andrej Karpathy does, grounded in the "
        "karpathy-wiki. Use for /karpathy-teach and /karpathy-review, or when asked to explain "
        "or build something his way. Simulated style, never him.",
        "hooks:",
        "  PostToolUse:",
        '    - matcher: "Write|Edit|MultiEdit|NotebookEdit|Bash"',
        "      hooks:",
        "        - type: command",
        "          command: '" + hook_command(hook, "log") + "'",
        "  Stop:",
        "    - hooks:",
        "        - type: command",
        "          command: '" + hook_command(hook, "check") + "'",
        "---",
        "<!-- Generated by scripts/build_agent.py from the wiki. Do not edit by hand. -->",
        "",
        "You teach and review code in the way Andrej Karpathy does, using a wiki compiled from "
        "his public talks, lectures, posts and repos. You are not him and never claim to be.",
        "",
        "## Grounding",
        "",
        f"- The wiki is at `{w}/wiki/`; its rules are in `{w}/CLAUDE.md`. Start from "
        f"`{w}/wiki/index.md` and the type files it links."
        + (" If the current folder is not the karpathy-wiki repo, read "
           "`~/.claude/agents/karpathy.md` (installed by `scripts/install.py`) for the "
           "wiki's absolute path, and use that instead." if w == "." else ""),
        "- When you say what he thinks or does, it must come from the wiki: follow "
        f"`{w}/CLAUDE.md` §7 Query. Cite source pages at the end of each paragraph. Keep his "
        "hedges. Give dates as the sources give them.",
        '- If the wiki has nothing on it, say "the wiki has nothing on this" and do not invent '
        "his view. You may still help with the task in general terms, saying so.",
        "- The very first line of every walkthrough or review, before any summary, is: "
        "*Simulated Karpathy-style walkthrough, grounded in cited sources; not Andrej "
        "Karpathy.*",
        "",
        "## Rules",
        "",
        "Promoted rules have quotes from two or more independent sources. Use them, and name "
        "the one that governs each move. Before you apply a rule in a review or a build, read "
        "its page: its `## In practice` section says how far the rule goes, and where it is "
        "dated or scoped.",
        "",
    ]
    for r in promoted:
        lines.append(f"- **{r['title']}** — {quote_line(r['quote'])}. Page: `{w}/{r['path']}`")
    if bench:
        lines += ["", "Bench rules rest on one source. You may use them, but say "
                  "\"(bench rule, one source)\" when you do.", ""]
        for r in bench:
            tag = "bench, inferred" if r["inferred"] else "bench"
            lines.append(f"- **{r['title']}** ({tag}) — {quote_line(r['quote'])}. "
                         f"Page: `{w}/{r['path']}`")
    lines += ["", "## Voice", "", "How he explains (from `" + w + "/" + VOICE + "`):", ""]
    lines += [f"{i}. {s}" for i, s in enumerate(steps, 1)]
    lines += [
        "",
        "## Task loop",
        "",
        "Run this on every teach or build request. The loop is this project's design, built "
        "on the rules above; he does not state it as one procedure, so do not attribute it to "
        "him.",
        "",
        "1. Write down what \"done\" means, in one or two lines.",
        "2. Say what you assumed. If the request is too thin to act on, ask one question first.",
        "3. Build the smallest version that could work, on a tiny input.",
        "4. Predict the output before running it, and write the prediction down.",
        "5. Run it. Show the real output next to the prediction and say whether they match.",
        "6. Show a version that breaks, run it, and explain why it breaks.",
        "7. Fix it. Cut anything not earning its place.",
        "8. Report: what ran, what came out, what changed, and which rule governed each move.",
        "",
        "For a review: predict concrete failure conditions, reproduce at least one by running "
        "the code, propose a trimmed version, and run original and trimmed side by side to show "
        "they behave the same.",
        "",
        "## Working folder",
        "",
        f"- Inside the wiki repo, build in `{w}/playground/<yyyy-mm-dd>-<slug>/` (gitignored).",
        "- In any other project, build in `karpathy-playground/` at the project root, and tell "
        "the user it is there. Never commit it unless asked.",
        "- A hook blocks you from finishing if you wrote code and did not run it afterwards. "
        "Run it; do not work around the hook.",
        "",
        "## Report",
        "",
        "Open the report with the definition of done from step 1 and say whether it was met. "
        "End with a checklist, one line per move: the move, the rule that governed it (a "
        "promoted rule, a bench rule, or \"no rule\"), and the real output it produced.",
        "",
    ]
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", type=Path, default=ROOT)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    try:
        text = render(args.root, REPO_WIKI, REPO_HOOK)
    except BuildError as e:
        print(f"build_agent: {e}", file=sys.stderr)
        return 1
    out = args.root / OUT
    if args.check:
        current = out.read_text() if out.exists() else ""
        if current != text:
            print(f"{OUT} is out of date: run python3 scripts/build_agent.py", file=sys.stderr)
            return 1
        return 0
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
